from fastapi import APIRouter, HTTPException
from pydantic import BaseModel
from typing import Optional

from app.models.c2_input import C2CandidatePackage
from app.models.patient_context import PatientContext
from app.models.safety_output import SafetyAssessmentReport
from app.core.safety_classifier import SafetyClassifier

router = APIRouter(
    prefix="/api/v1/c2",
    tags=["Component 2 Integration (C2 -> C3)"]
)

classifier = SafetyClassifier()


class C2SafetyEvaluationRequest(BaseModel):
    candidate_package: C2CandidatePackage
    patient_context: PatientContext


@router.post("/safety-evaluation", response_model=SafetyAssessmentReport)
def evaluate_c2_candidates(payload: C2SafetyEvaluationRequest):
    """Primary integration endpoint for Component 2 -> Component 3.

    Receives candidate Ayurvedic recommendations generated by C2 and
    evaluates their safety against the patient's medications, comorbidities,
    and organ functions before presenting to the practitioner.
    """
    try:
        report = classifier.evaluate_package(
            c2_package=payload.candidate_package,
            patient=payload.patient_context
        )
        return report
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Safety evaluation failed: {str(e)}")
