from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class CandidateItem(BaseModel):
    id: str = Field(..., description="Unique recommendation candidate ID, e.g., 'REC-PANDU-001'")
    name: str = Field(..., description="Ayurvedic herb or formulation name, e.g., 'Punarnava Mandura'")
    category: str = Field(..., description="Herb, Formulation, Diet, or Lifestyle")
    botanical_name: Optional[str] = Field(None, description="Botanical name if single herb, e.g., 'Boerhavia diffusa'")
    dose: Optional[str] = Field(None, description="Recommended standard dosage, e.g., '250 mg twice daily'")
    reasoning_score: float = Field(..., ge=0.0, le=1.0, description="Recommendation score generated by Component 2")
    rationale: str = Field(..., description="Ayurvedic reasoning rationale from C2")
    evidence_ids: List[str] = Field(default_factory=list, description="Classical or contemporary evidence reference IDs")


class C2CandidatePackage(BaseModel):
    case_id: str = Field(..., description="Unique case identifier, e.g., 'CASE-001'")
    anemia_risk_tier: str = Field(..., description="Anemia risk tier from C1: Low, Moderate, High")
    anemia_confidence: Optional[float] = Field(
        None, ge=0.0, le=1.0,
        description="C1 calibrated confidence score; null when Component 1 provides none",
    )
    ayurvedic_interpretation: str = Field(..., description="Dosha/Dhatu mapping, e.g. 'Pittaja Pandu Roga'")
    symptom_summary: List[str] = Field(default_factory=list, description="Reported symptoms: fatigue, pallor, etc.")
    candidates: List[CandidateItem] = Field(..., description="List of candidate herbs or formulations from C2")
    metadata: Optional[Dict[str, Any]] = Field(default_factory=dict)
