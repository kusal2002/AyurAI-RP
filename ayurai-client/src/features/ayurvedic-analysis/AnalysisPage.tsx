/** Labels that separate who produced each piece of information. */
export function OriginTag({ kind }: { kind: "model" | "knowledge" | "practitioner" }) {
  const map: Record<typeof kind, { label: string; icon: LucideIcon; className: string }> = {
    model: { label: "Generated by Component 2 reasoning", icon: Bot, className: "bg-sky-50 text-sky-800 ring-sky-200" },
    knowledge: { label: "From the knowledge base", icon: Database, className: "bg-teal-50 text-teal-800 ring-teal-200" },
    practitioner: { label: "Practitioner review", icon: UserCheck, className: "bg-emerald-50 text-emerald-800 ring-emerald-200" },
  }
  const { label, icon: Icon, className } = map[kind]
  return (
    <span className={`inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[10px] font-semibold ring-1 ring-inset ${className}`}>
      <Icon aria-hidden className="size-3" /> {label}
    </span>
  )
}

const typeOrder = ["Roga", "Dosha", "Dhatu", "TherapeuticPrinciple"]

function InterpretationSection({ output }: { output: Component2Output }) {
  const groups = React.useMemo(() => {
    const byType = new Map<string, Component2Output["interpretation"]>()
    for (const concept of output.interpretation) {
      byType.set(concept.concept_type, [...(byType.get(concept.concept_type) ?? []), concept])
    }
    return Array.from(byType.entries()).sort(
      ([a], [b]) => (typeOrder.indexOf(a) + 1 || 99) - (typeOrder.indexOf(b) + 1 || 99),
    )
  }, [output])

  if (output.interpretation.length === 0) {
    return (
      <EmptyState
        icon={CircleSlash}
        title="No Ayurvedic interpretation was produced"
        description="Graph traversal did not reach any Roga, Dosha, Dhatu or therapeutic-principle concept for the supplied symptoms. Nothing is inferred in its place."
      />
    )
  }

  return (
    <div className="space-y-4">
      <Notice tone="neutral">
        Reaching a concept is a knowledge-graph association through evidence-linked claims, not a
        diagnosis. Pandu Roga relevance is shown only when a Roga concept is returned by the service.
      </Notice>
      {groups.map(([type, concepts]) => (
        <div key={type}>
          <h3 className="mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">
            {conceptTypeLabels[type] ?? type}
          </h3>
          <ul className="grid grid-cols-1 gap-3 md:grid-cols-2">
            {concepts.map((concept) => (
              <li key={concept.concept_id} className="rounded-xl border border-slate-200 p-3">
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <div className="min-w-0">
                    <p className="font-semibold text-slate-900">{concept.name ?? "Name not supplied"}</p>
                    <IdChip>{concept.concept_id}</IdChip>
                  </div>
                  <div className="flex flex-wrap gap-1">
                    {Array.from(new Set(concept.verification_statuses)).map((status) => (
                      <StatusBadge key={status} spec={verificationSpec(status)} />
                    ))}
                  </div>
                </div>
                <p className="mt-2 text-xs text-slate-600">
                  Reached via {concept.via_claim_ids.length} claim{concept.via_claim_ids.length === 1 ? "" : "s"} ·{" "}
                  <span className="text-emerald-800">{concept.supporting_evidence_ids.length} supporting</span> ·{" "}
                  <span className={concept.contradicting_evidence_ids.length ? "font-semibold text-rose-700" : ""}>
                    {concept.contradicting_evidence_ids.length} contradicting
                  </span>{" "}
                  evidence record{concept.contradicting_evidence_ids.length === 1 ? "" : "s"}
                </p>
              </li>
            ))}
          </ul>
        </div>
      ))}
    </div>
  )
}

function evidenceRefsFor(output: Component2Output, relationship: EvidenceReference["relationship"]) {
  const index = indexEvidence(output)
  const ids = new Set(
    output.interpretation.flatMap((concept) =>
      relationship === "SUPPORTS" ? concept.supporting_evidence_ids : concept.contradicting_evidence_ids,
    ),
  )
  const refs: EvidenceReference[] = []
  for (const id of ids) {
    const entry = index.get(id)
    refs.push(
      entry
        ? { ...entry.reference, relationship }
        : {
            evidence_id: id,
            relationship,
            title: null,
            source_name: null,
            evidence_type: null,
            section: null,
            page: null,
            citation: null,
            source_url: null,
            practitioner_verified: false,
            provenance_complete: false,
            missing_provenance: ["metadata_not_in_response"],
          },
    )
  }
  return refs
}

function SafetyStatus({ record }: { record: CaseRecord }) {
  const state = record.c3
  if (state.status === "success") {
    return (
      <div className="space-y-3">
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-sm text-slate-600">Overall classification from Component 3:</span>
          <StatusBadge size="md" spec={safetySpec(state.data.overall_safety_tier)} />
        </div>
        <p className="text-xs text-slate-500">
          Assessment <IdChip>{state.data.assessment_id}</IdChip> · {state.data.evaluations.length} candidate
          {state.data.evaluations.length === 1 ? "" : "s"} evaluated · practitioner review required:{" "}
          {state.data.practitioner_review_required ? "yes" : "no"}
        </p>
        <Button variant="outline" size="sm" render={<Link to="/safety" />} nativeButton={false}>
          Open safety assessment
        </Button>
      </div>
    )
  }
  return (
    <div className="flex flex-wrap items-center justify-between gap-3">
      <p className="text-sm text-slate-600">
        {state.status === "loading"
          ? "Safety assessment in progress…"
          : state.status === "error"
            ? `Safety assessment failed: ${state.error.message}`
            : "No Component 3 safety assessment yet. Candidates are not cleared for use until it runs and a practitioner reviews it."}
      </p>
      <Button variant="outline" size="sm" render={<Link to="/safety" />} nativeButton={false}>
        Go to safety assessment
      </Button>
    </div>
  )
}

function ReasoningDetail({ output, record }: { output: Component2Output; record: CaseRecord }) {
  const { runReasoning } = useWorkspace()
  const names = React.useMemo(() => conceptNames(output), [output])
  const supporting = React.useMemo(() => evidenceRefsFor(output, "SUPPORTS"), [output])
  const contradicting = React.useMemo(() => evidenceRefsFor(output, "CONTRADICTS"), [output])
  const mapped = output.symptom_mappings.filter((mapping) => mapping.found).length
  const feedbackRecorded = record.feedback.filter((entry) => entry.outcome.status === "recorded").length

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-xl border border-slate-200 bg-white px-4 py-3">
        <div className="flex flex-wrap items-center gap-2">
          {output.abstention.abstain ? (
            <StatusBadge size="md" spec={abstentionSpec} />
          ) : (
            <StatusBadge size="md" spec={sufficiencySpec(output.sufficiency_status)} />
          )}
          {output.review_required && (
            <span className="text-xs font-medium text-slate-600">Practitioner review required</span>
          )}
        </div>
        <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500">
          <span>Generated {formatDateTime(output.generated_at)}</span>
          <span>· schema {output.schema_version}</span>
          <Button variant="outline" size="sm" onClick={() => runReasoning(record.id)}>
            <RefreshCw /> Re-run
          </Button>
        </div>
      </div>

      <div className="flex flex-wrap gap-2 text-xs text-slate-500">
        <span>Information origin:</span>
        <OriginTag kind="model" />
        <OriginTag kind="knowledge" />
        <OriginTag kind="practitioner" />
      </div>

      <Panel step={1} title="Input case and screening result" description="Upstream Component 1 metadata and symptom-to-concept mapping">
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <div>
            <KeyValueList
              items={[
                { label: "Case reference", value: record.caseRef },
                { label: "Component 1 risk tier", value: <span className="capitalize">{output.upstream.risk_tier}</span> },
                { label: "Component 1 calibrated confidence", value: formatScore(output.upstream.calibrated_confidence) },
                { label: "Summary origin", value: record.c1?.origin === "demo_fixture" ? "Demo fixture" : "Manual entry of approved C1 result" },
                { label: "Symptoms mapped", value: `${mapped} of ${output.symptom_mappings.length}` },
              ]}
            />
            <div className="mt-2">
              <ScoreCaveat>
                The screening confidence is upstream metadata only. Component 2 does not reuse it as confidence in any
                Ayurvedic concept or candidate.
              </ScoreCaveat>
            </div>
          </div>
          <ul className="space-y-2">
            {output.symptom_mappings.map((mapping) => (
              <li key={mapping.symptom_id} className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-slate-200 px-3 py-2">
                <div className="min-w-0">
                  <p className="text-sm font-medium text-slate-800">{mapping.name ?? "Not found in the knowledge graph"}</p>
                  <IdChip>{mapping.symptom_id}</IdChip>
                  {mapping.message && <p className="mt-0.5 text-xs text-slate-500">{mapping.message}</p>}
                </div>
                {mapping.found ? (
                  <StatusBadge spec={{ label: `Mapped · ${mapping.indicates_claim_ids.length} claim(s)`, tone: "positive", icon: CheckCircle2 }} />
                ) : (
                  <StatusBadge spec={{ label: "Not mapped", tone: "caution", icon: CircleSlash }} />
                )}
              </li>
            ))}
          </ul>
        </div>
      </Panel>

      <Panel step={2} title="Ayurvedic interpretation" description="Roga, Dosha, Dhatu and therapeutic-principle concepts reached through claims" actions={<OriginTag kind="model" />}>
        <InterpretationSection output={output} />
      </Panel>

      <Panel step={3} title="Reasoning summary" description="Deterministic explanation statements with their claim and evidence provenance" actions={<OriginTag kind="model" />}>
        <ExplanationList statements={output.explanation} />
      </Panel>

      <Panel
        step={4}
        title="Evidence supporting the interpretation"
        description="Evidence records linked to the claims that reached the interpreted concepts"
        actions={
          <>
            <OriginTag kind="knowledge" />
            <Link to="/evidence" className="text-xs font-semibold text-emerald-700 hover:text-emerald-900">
              Evidence explorer
            </Link>
          </>
        }
      >
        {supporting.length === 0 ? (
          <p className="text-sm text-slate-500">No supporting evidence is linked to the interpretation.</p>
        ) : (
          <ul className="space-y-2">
            {supporting.map((reference) => (
              <EvidenceReferenceRow key={reference.evidence_id} reference={reference} />
            ))}
          </ul>
        )}
        <p className="mt-3 text-xs text-slate-500">
          The reasoning response carries evidence metadata, not source passages. Full source text is not
          available from the current API.
        </p>
      </Panel>

      <Panel step={5} title="Conflicting evidence and limitations">
        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <div>
            <h3 className="mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">Contradicting evidence (interpretation)</h3>
            {contradicting.length === 0 ? (
              <p className="text-sm text-slate-500">None linked to the interpreted concepts.</p>
            ) : (
              <ul className="space-y-2">
                {contradicting.map((reference) => (
                  <EvidenceReferenceRow key={reference.evidence_id} reference={reference} />
                ))}
              </ul>
            )}
            <h3 className="mt-5 mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">Evidence gaps</h3>
            <FlagList flags={output.evidence_gaps} />
          </div>
          <div>
            <h3 className="mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">Uncertainty flags</h3>
            <FlagList flags={output.uncertainty_flags} />
            {output.traversal_truncated && (
              <p className="mt-2 text-sm font-medium text-amber-800">Graph traversal was truncated; some paths may be missing.</p>
            )}
            <h3 className="mt-5 mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">Semantic retrieval</h3>
            <KeyValueList
              items={[
                { label: "Mode", value: output.retrieval.mode.replace(/_/g, " ") },
                { label: "Model", value: output.retrieval.model_id ?? "—" },
                { label: "Indexed chunks", value: output.retrieval.indexed_chunks },
                { label: "Similarity threshold", value: formatScore(output.retrieval.min_similarity) },
                ...(output.retrieval.error ? [{ label: "Error", value: output.retrieval.error }] : []),
              ]}
            />
          </div>
        </div>
        {output.rejected_paths.length > 0 && (
          <div className="mt-5">
            <h3 className="mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">
              Rejected paths ({output.rejected_paths.length})
            </h3>
            <ul className="space-y-2">
              {output.rejected_paths.map((path, index) => (
                <li key={index} className="rounded-lg border border-slate-200 px-3 py-2">
                  <ConceptPath ids={path.concept_ids} names={names} />
                  <p className="mt-1 text-xs text-slate-600">{describeFlag(path.reason).label}</p>
                </li>
              ))}
            </ul>
          </div>
        )}
        <div className="mt-5">
          <h3 className="mb-2 text-xs font-semibold tracking-wide text-slate-500 uppercase">Stated limitations</h3>
          <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700">
            {output.limitations.map((limitation) => (
              <li key={limitation}>{limitation}</li>
            ))}
          </ul>
        </div>
      </Panel>

      <Panel
        step={6}
        title="Ranked candidates"
        description="Herb, formulation, diet and lifestyle candidates produced by the system (not practitioner-approved recommendations)"
        actions={
          <Link to="/candidates" className="text-xs font-semibold text-emerald-700 hover:text-emerald-900">
            Candidate details
          </Link>
        }
      >
        {output.candidates.length === 0 ? (
          <EmptyState icon={CircleSlash} title="No candidates generated" description="Component 2 returned no valid candidate path." />
        ) : (
          <ol className="space-y-2">
            {output.candidates.map((candidate) => (
              <li key={candidate.candidate_id} className="flex flex-wrap items-center justify-between gap-2 rounded-lg border border-slate-200 px-3 py-2">
                <div className="flex min-w-0 items-center gap-3">
                  <span className="flex size-7 shrink-0 items-center justify-center rounded-full bg-slate-100 text-xs font-bold text-slate-700">
                    {candidate.rank}
                  </span>
                  <div className="min-w-0">
                    <p className="text-sm font-semibold text-slate-800">{candidate.name ?? candidate.candidate_id}</p>
                    <p className="text-xs text-slate-500">
                      {candidate.category} · experimental ranking score {formatScore(candidate.ranking.score)}
                    </p>
                  </div>
                </div>
                <div className="flex flex-wrap gap-1.5">
                  <StatusBadge spec={sufficiencySpec(candidate.sufficiency.status)} />
                  <StatusBadge spec={dispositionSpec(candidate.disposition)} />
                </div>
              </li>
            ))}
          </ol>
        )}
        <div className="mt-3">
          <ScoreCaveat>{output.score_semantics["ranking.score"] ?? "Experimental ranking score; not clinical confidence."}</ScoreCaveat>
        </div>
      </Panel>

      <Panel step={7} title="Uncertainty and abstention status">
        {output.abstention.abstain ? (
          <div className="rounded-xl border border-amber-200 bg-amber-50/60 p-4">
            <StatusBadge size="md" spec={abstentionSpec} />
            {output.abstention.explanation && <p className="mt-2 text-sm text-amber-900">{output.abstention.explanation}</p>}
            <div className="mt-3">
              <FlagList flags={output.abstention.reasons} />
            </div>
            <p className="mt-3 text-xs text-amber-900">
              No recommendation is shown in place of the abstention. A practitioner should review the case directly.
            </p>
          </div>
        ) : (
          <div className="space-y-2 text-sm text-slate-700">
            <p className="flex flex-wrap items-center gap-2">
              Component 2 did not abstain. Request-level status:
              <StatusBadge spec={sufficiencySpec(output.sufficiency_status)} />
            </p>
            <p className="text-xs text-slate-500">
              {sufficiencySpec(output.sufficiency_status).description} Sufficiency rules are a provisional prototype policy.
            </p>
          </div>
        )}
      </Panel>

      <Panel step={8} title="Safety assessment status" description="Component 3 safety gate" actions={<BookOpen aria-hidden className="size-4 text-slate-400" />}>
        <SafetyStatus record={record} />
      </Panel>

      <Panel step={9} title="Practitioner review status" actions={<OriginTag kind="practitioner" />}>
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="text-sm text-slate-700">
            <p>
              {record.feedback.length === 0
                ? "No practitioner feedback has been recorded for this case in this session."
                : `${record.feedback.length} feedback submission(s) in this session; ${feedbackRecorded} recorded by the Component 2 service.`}
            </p>
            <p className="mt-1 text-xs text-slate-500">
              Final approval is not available: no Component 4 decision service exists. Nothing has been approved.
            </p>
          </div>
          <Button className="bg-emerald-700 hover:bg-emerald-800" size="sm" render={<Link to="/review" />} nativeButton={false}>
            Open practitioner review
          </Button>
        </div>
      </Panel>
    </div>
  )
}

